// Funzione per ottenere 3-5 affermazioni random per mood
export const getAffirmationsForMood = (mood, count = 3) => {
  const moodAffirmations = affirmations[mood] || affirmations.incerto;
  const shuffled = [...moodAffirmations].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};
